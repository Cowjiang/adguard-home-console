#!/usr/bin/env bash
# Prints the delta between the vendored tauri-plugin-system-components fork
# (src-tauri/plugins/) and the upstream crate release it is based on, so
# "what did we change" is one command instead of a hand-made diff.
#
# Upstream source comes from the local cargo registry when it is there; on a
# fresh clone it is not, because the crate is patched out and cargo never
# downloads it — so fall back to fetching the .crate from crates.io into a
# temporary directory. Baseline and the delta rationale live in
# src-tauri/plugins/tauri-plugin-system-components/FORK.md.
#
# Usage: scripts/plugin-fork-diff.sh [--stat]
#   --stat  file-level summary only (name status per file)
set -euo pipefail

root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
plugin="$root/src-tauri/plugins/tauri-plugin-system-components"
name=tauri-plugin-system-components
version=$(sed -n 's/^version = "\(.*\)"/\1/p' "$plugin/Cargo.toml" | head -1)

# Generated permission files and packaging metadata differ by construction (or
# were deliberately dropped); FORK.md explains both. Excluding them keeps the
# output on the code delta that has to be replayed on an upstream bump.
excludes=(
  -x target -x node_modules -x dist-js -x .build -x .tauri -x Package.resolved
  -x autogenerated -x schemas
  -x Cargo.lock -x Cargo.toml.orig -x .cargo-ok -x .cargo_vcs_info.json
)

tmp=""
cleanup() {
  if [ -n "$tmp" ]; then rm -rf "$tmp"; fi
}
trap cleanup EXIT

upstream=$(find "${CARGO_HOME:-$HOME/.cargo}/registry/src" -maxdepth 2 -type d \
  -name "$name-$version" 2>/dev/null | head -1)
if [ -z "$upstream" ]; then
  echo "no local registry copy of $name-$version; downloading from crates.io" >&2
  tmp=$(mktemp -d)
  curl -fsSL "https://crates.io/api/v1/crates/$name/$version/download" |
    tar xz -C "$tmp"
  upstream="$tmp/$name-$version"
  [ -d "$upstream" ] || { echo "download did not contain $name-$version" >&2; exit 1; }
fi

echo "# upstream $name $version  ($upstream)"
echo "# fork     $plugin"
echo

# Line prefixes a diff in our direction: "+" only in the fork, "-" only upstream.
if [ "${1:-}" = "--stat" ]; then
  diff -rq "${excludes[@]}" "$upstream" "$plugin" || true
else
  diff -ru "${excludes[@]}" "$upstream" "$plugin" || true
fi
